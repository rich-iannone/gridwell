//! The Rust code blocks of the docs, as test functions. Shared by `build.rs`, which
//! writes them to `OUT_DIR` for `tests/rust_snippets.rs` to compile and run, and by
//! that test, which checks the extraction itself.
//!
//! A block is a fence whose info string is `rust` or `{.rust …}`, on a docs page
//! (`docs/**/*.qmd`) or a README. It runs as the body of a function given `json`
//! (the getting-started table's IR), `table` (that table, parsed) and `input`
//! (`&json`), whose errors `?` returns. `<!-- docs-check: skip -->` on the line
//! before a fence (blank lines aside) leaves the block out.

use std::path::{Path, PathBuf};

pub const SKIP: &str = "<!-- docs-check: skip -->";

/// The READMEs checked besides `docs/`.
pub const READMES: [&str; 4] = [
    "README.md",
    "crates/gridwell/README.md",
    "crates/gridwell-cli/README.md",
    "conformance/README.md",
];

/// A Rust block: where it is (the line of its opening fence) and its code.
#[derive(Debug, PartialEq)]
pub struct Snippet {
    pub page: String,
    pub line: usize,
    pub code: String,
}

/// The pages, repo-relative with `/`, sorted.
pub fn pages(root: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let mut dirs = vec![root.join("docs")];
    while let Some(dir) = dirs.pop() {
        for entry in std::fs::read_dir(&dir).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                if !path.ends_with("_site") && !path.ends_with(".quarto") {
                    dirs.push(path);
                }
            } else if path.extension().is_some_and(|e| e == "qmd") {
                out.push(path.strip_prefix(root).unwrap().to_path_buf());
            }
        }
    }
    out.extend(READMES.iter().map(PathBuf::from));
    out.sort();
    out
}

fn is_rust(info: &str) -> bool {
    info == "rust" || info.starts_with("{.rust}") || info.starts_with("{.rust ")
}

/// The Rust blocks of one page.
pub fn snippets(page: &str, text: &str) -> Vec<Snippet> {
    let mut out = Vec::new();
    // The opening fence's line, its backtick count, whether it's kept, and the code.
    let mut open: Option<(usize, usize, bool, String)> = None;
    let mut skip_next = false;
    for (i, line) in text.lines().enumerate() {
        let t = line.trim_end();
        match &mut open {
            None if t.starts_with("```") => {
                let info = t.trim_start_matches('`');
                let ticks = t.len() - info.len();
                let keep = is_rust(info.trim()) && !skip_next;
                open = Some((i + 1, ticks, keep, String::new()));
                skip_next = false;
            }
            None => {
                if t.trim() == SKIP {
                    skip_next = true;
                } else if !t.trim().is_empty() {
                    skip_next = false;
                }
            }
            Some((start, ticks, keep, code)) => {
                if t.len() >= *ticks && t.chars().all(|c| c == '`') {
                    if *keep {
                        out.push(Snippet {
                            page: page.to_string(),
                            line: *start,
                            code: std::mem::take(code),
                        });
                    }
                    open = None;
                } else {
                    code.push_str(line);
                    code.push('\n');
                }
            }
        }
    }
    out
}

impl Snippet {
    pub fn location(&self) -> String {
        format!("{}:{}", self.page, self.line)
    }

    fn function(&self) -> String {
        let name: String = self
            .location()
            .chars()
            .map(|c| {
                if c.is_ascii_alphanumeric() {
                    c.to_ascii_lowercase()
                } else {
                    '_'
                }
            })
            .collect();
        format!("snippet_{name}")
    }
}

/// The snippets as Rust source: a function each, and `SNIPPETS`, their locations
/// and functions.
pub fn generate(snippets: &[Snippet]) -> String {
    let mut out =
        String::from("// Generated by xtask/build.rs from the docs' Rust blocks. Do not edit.\n\n");
    for s in snippets {
        let mut body = String::new();
        for line in s.code.lines() {
            body.push_str("        ");
            body.push_str(line);
            body.push('\n');
        }
        out.push_str(&format!(
            "// {}\n#[allow(unused, clippy::all)]\nfn {}(json: String, table: gridwell::Table) \
             -> Result<(), Box<dyn std::error::Error>> {{\n    let input: &str = &json;\n    {{\n\
             {body}    }}\n    Ok(())\n}}\n\n",
            s.location(),
            s.function(),
        ));
    }
    out.push_str(
        "type Snippet = fn(String, gridwell::Table) -> Result<(), Box<dyn std::error::Error>>;\n\n",
    );
    out.push_str("const SNIPPETS: &[(&str, Snippet)] = &[\n");
    for s in snippets {
        out.push_str(&format!("    ({:?}, {}),\n", s.location(), s.function()));
    }
    out.push_str("];\n");
    out
}
