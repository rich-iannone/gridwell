    #[test]
    fn crate_manifest_rejects_what_it_cannot_bundle() {
        let reject = |p: Value, needle: &str| {
            let err = crate_manifest(&p, &locals(), "crates/gridwell-ir/Cargo.toml").unwrap_err();
            assert!(err.contains(needle), "{err}");
        };
        let mut p = pkg(json!([]), lib());
        p["links"] = json!("z");
        reject(p, "links");

        let mut build = dep("cc");
        build["kind"] = json!("build");
        reject(pkg(json!([build]), lib()), "build-dependency `cc`");

        let mut git = dep("serde");
        git["source"] = json!("git+https://github.com/serde-rs/serde");
        reject(pkg(json!([git]), lib()), "only crates.io and the workspace");

        let mut stray = dep("gridwell-layout");
        stray["path"] = json!("/repo/crates/gridwell-layout");
        stray["source"] = Value::Null;
        reject(
            pkg(json!([stray]), lib()),
            "isn't one of the bundled crates",
        );

        let mut targets = lib();
        targets.as_array_mut().unwrap().push(json!(
            {"kind": ["custom-build"], "name": "build-script-build", "src_path": "/repo/crates/gridwell-ir/build.rs"}
        ));
        reject(pkg(json!([]), targets), "custom-build");

        let bin = json!([{"kind": ["bin"], "name": "gw", "src_path": "/repo/crates/gridwell-ir/src/main.rs"}]);
        reject(pkg(json!([]), bin), "only a library at src/lib.rs");

        let moved = json!([{"kind": ["lib"], "name": "gridwell_ir", "src_path": "/repo/crates/gridwell-ir/lib.rs"}]);
        reject(pkg(json!([]), moved), "only a library at src/lib.rs");

        reject(pkg(json!([]), json!([])), "no library target");
    }

    #[test]
    fn glue_manifest_points_at_bundled_crates() {
        let original = "[package]\nname = \"gridwell-r\"\n\n[dependencies]\n\
            gridwell-ir = { path = \"../../../crates/gridwell-ir\" }\n\
            gridwell-render = { path = \"../../../crates/gridwell-render\" }\n";
        let m = glue_manifest(original).unwrap();
        assert!(m.starts_with(GENERATED));
        assert!(m.contains("gridwell-ir = { path = \"crates/gridwell-ir\" }"));
        assert!(m.contains("gridwell-render = { path = \"crates/gridwell-render\" }"));
        assert!(m.trim_end().ends_with("[workspace]"));

        let elsewhere = format!("{original}other = {{ path = \"../../other\" }}\n");
        assert!(glue_manifest(&elsewhere)
            .unwrap_err()
            .contains("outside the package"));
        assert!(glue_manifest("[package]\n")
            .unwrap_err()
            .contains("no `../../../crates/`"));
        let with_workspace = format!("{original}[workspace]\n");
        assert!(glue_manifest(&with_workspace)
            .unwrap_err()
            .contains("[workspace]"));
    }

