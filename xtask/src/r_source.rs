    #[test]
    fn clear_output_replaces_only_its_own_output() {
        let base = std::env::temp_dir().join(format!("gridwell-r-source-{}", std::process::id()));
        let out = base.join("gridwell");
        let _ = std::fs::remove_dir_all(&base);

        clear_output(&out).unwrap();
        std::fs::create_dir_all(&out).unwrap();
        clear_output(&out).unwrap();
        assert!(!out.exists(), "an empty directory is replaced");

        // What a run that failed after writing the glue manifest leaves.
        write(
            &out.join("src/rust/Cargo.toml"),
            &glue_manifest("x = { path = \"../../../crates/x\" }\n").unwrap(),
        )
        .unwrap();
        write(&out.join("R/a.R"), "").unwrap();
        clear_output(&out).unwrap();
        assert!(!out.exists(), "an earlier output is replaced");

        write(&out.join("src/rust/Cargo.toml"), "[package]\n").unwrap();
        let err = clear_output(&out).unwrap_err();
        assert!(err.contains("isn't an earlier r-source output"), "{err}");
        write(&out.join("src/rust/Cargo.toml"), "").unwrap();
        std::fs::remove_file(out.join("src/rust/Cargo.toml")).unwrap();
        assert!(
            clear_output(&out).is_err(),
            "a directory with other files is kept"
        );
        assert!(out.join("src/rust").is_dir());

        std::fs::remove_dir_all(&base).unwrap();
    }
