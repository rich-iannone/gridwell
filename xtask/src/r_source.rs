//! `cargo xtask r-source`: the R package as a self-contained source package, the
//! form CRAN and r-universe build from.
//!
//! In the repository the R glue crate (`r-package/src/rust`) depends on the
//! workspace crates by path, outside the package, and its tests read the
//! repository's `fixtures/`, so a tarball that `R CMD build` makes of `r-package`
//! can't be installed or checked. This writes a copy of the package that carries
//! everything it needs:
//!
//! - the workspace crates the glue crate uses, in `src/rust/crates/<name>`: their
//!   `src/` and a manifest written from `cargo metadata`, with the workspace
//!   inheritance resolved and no dev-dependencies;
//! - the glue crate's manifest, pointing at them and made its own workspace;
//! - every crates.io dependency, vendored from the same `Cargo.lock`, in
//!   `src/rust/vendor.tar.xz`, with `src/rust/vendor-config.toml` pointing cargo at
//!   it (`src/Makevars*` and `tools/config.R` then build offline);
//! - `inst/AUTHORS`, the authors and licenses of the bundled crates, named in
//!   DESCRIPTION's `Copyright` field, as CRAN asks;
//! - the JSON fixtures the tests read, in `tests/testthat/fixtures`.
//!
//! `R CMD build` of the copy then makes the package tarball. Files come from git
//! (tracked, plus untracked ones not ignored), so build products never leak in.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use serde_json::Value;

/// The first line of the glue crate's generated manifest; marks an output
/// directory as one this wrote, safe to replace.
const GENERATED: &str = "# Generated by `cargo xtask r-source`";

const CRATES_IO: &str = "registry+https://github.com/rust-lang/crates.io-index";

/// Points cargo at the vendored crates. `src/Makevars*` copy it to
/// `$CARGO_HOME/config.toml`, so `vendor` is relative to `src/`, where they unpack
/// `vendor.tar.xz`.
const VENDOR_CONFIG: &str = "\
[source.crates-io]
replace-with = \"vendored-sources\"

[source.vendored-sources]
directory = \"vendor\"
";

/// Write the source package to `out` (default `target/r-source/gridwell`) and
/// return a summary.
pub fn run(root: &Path, out: Option<PathBuf>) -> Result<String, String> {
    let out = out.unwrap_or_else(|| root.join("target/r-source/gridwell"));
    let pkg = root.join("r-package");
    let manifest = pkg.join("src/rust/Cargo.toml");
    let metadata = cargo_metadata(&manifest)?;
    let locals = local_packages(&metadata)?;
    let glue = glue_manifest(&read(&manifest)?)?;

    clear_output(&out)?;
    // First, so that a run that fails later leaves an output the next one replaces.
    write(&out.join("src/rust/Cargo.toml"), &glue)?;
    for rel in git_files(root, "r-package")? {
        let rel_out = rel
            .strip_prefix("r-package")
            .expect("listed under r-package");
        if rel_out != Path::new("src/rust/Cargo.toml") {
            copy(&root.join(&rel), &out.join(rel_out))?;
        }
    }
    for rel in git_files(root, "fixtures")? {
        if rel.extension().is_some_and(|e| e == "json") {
            copy(&root.join(&rel), &out.join("tests/testthat").join(&rel))?;
        }
    }

    let names: BTreeSet<&str> = locals.iter().map(|p| p.name.as_str()).collect();
    for local in &locals {
        let dir = out.join("src/rust/crates").join(&local.name);
        let src = local.dir.join("src");
        let src_rel = src
            .strip_prefix(root)
            .map_err(|_| format!("{} is outside the repository", src.display()))?;
        for rel in git_files(root, &src_rel.to_string_lossy())? {
            let dest = dir
                .join("src")
                .join(rel.strip_prefix(src_rel).expect("listed under src"));
            copy(&root.join(&rel), &dest)?;
        }
        let origin = local.dir.join("Cargo.toml");
        let origin = origin.strip_prefix(root).expect("checked above");
        let manifest = crate_manifest(&local.json, &names, &origin.to_string_lossy())?;
        write(&dir.join("Cargo.toml"), &manifest)?;
    }

    let description = read(&pkg.join("DESCRIPTION"))?;
    write(&out.join("DESCRIPTION"), &with_copyright(&description)?)?;
    write(&out.join("inst/AUTHORS"), &authors(&metadata)?)?;

    verify(
        &metadata,
        &cargo_metadata(&out.join("src/rust/Cargo.toml"))?,
    )?;
    let size = vendor(&out.join("src/rust"))?;
    Ok(format!(
        "wrote {} with {} workspace crates and a {:.1} MB vendor.tar.xz\n\
         next: R CMD build {}\n",
        out.display(),
        locals.len(),
        size as f64 / 1e6,
        out.display(),
    ))
}

/// The packages and dependency edges of a resolve: `name version` (with `(path)`
/// for path packages) to the same for each dependency.
fn resolve_graph(metadata: &Value) -> Result<BTreeMap<String, BTreeSet<String>>, String> {
    let mut label = BTreeMap::new();
    for p in metadata["packages"]
        .as_array()
        .ok_or("cargo metadata: no packages")?
    {
        let path = if p["source"].is_null() { " (path)" } else { "" };
        label.insert(
            str_field(p, "id")?,
            format!(
                "{} {}{path}",
                str_field(p, "name")?,
                str_field(p, "version")?
            ),
        );
    }
    let mut graph = BTreeMap::new();
    for node in metadata["resolve"]["nodes"]
        .as_array()
        .ok_or("cargo metadata: no resolve")?
    {
        let deps = node["dependencies"]
            .as_array()
            .ok_or("cargo metadata: no node dependencies")?
            .iter()
            .filter_map(Value::as_str)
            .map(|id| label[id].clone())
            .collect();
        graph.insert(label[str_field(node, "id")?].clone(), deps);
    }
    Ok(graph)
}

/// The written package must resolve to the same graph as the repository's glue
/// crate (from the same `Cargo.lock`, `--locked`), and every bundled library's
/// source must be there.
fn verify(original: &Value, written: &Value) -> Result<(), String> {
    if resolve_graph(original)? != resolve_graph(written)? {
        return Err("the written package resolves to a different dependency graph".into());
    }
    let packages = written["packages"].as_array().into_iter().flatten();
    for p in packages.filter(|p| p["source"].is_null()) {
        for target in p["targets"].as_array().into_iter().flatten() {
            let src = Path::new(str_field(target, "src_path")?);
            if !src.is_file() {
                return Err(format!("{} is missing", src.display()));
            }
        }
    }
    Ok(())
}

/// A path dependency of the glue crate (directly or not): a workspace crate.
struct Local {
    name: String,
    dir: PathBuf,
    json: Value,
}

fn cargo() -> Command {
    Command::new(std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into()))
}

fn run_command(mut cmd: Command, what: &str) -> Result<Vec<u8>, String> {
    let output = cmd.output().map_err(|e| format!("{what}: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "{what} failed ({}):\n{}",
            output.status,
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    Ok(output.stdout)
}

fn cargo_metadata(manifest: &Path) -> Result<Value, String> {
    let mut cmd = cargo();
    cmd.args([
        "metadata",
        "--format-version",
        "1",
        "--locked",
        "--manifest-path",
    ])
    .arg(manifest);
    let stdout = run_command(cmd, "cargo metadata")?;
    serde_json::from_slice(&stdout).map_err(|e| format!("cargo metadata output: {e}"))
}

fn str_field<'a>(value: &'a Value, key: &str) -> Result<&'a str, String> {
    value
        .get(key)
        .and_then(Value::as_str)
        .ok_or_else(|| format!("cargo metadata: no string `{key}`"))
}

fn local_packages(metadata: &Value) -> Result<Vec<Local>, String> {
    let root = str_field(&metadata["resolve"], "root")?;
    let packages = metadata["packages"]
        .as_array()
        .ok_or("cargo metadata: no packages")?;
    let mut locals = Vec::new();
    for p in packages {
        if !p["source"].is_null() || str_field(p, "id")? == root {
            continue;
        }
        let manifest = PathBuf::from(str_field(p, "manifest_path")?);
        locals.push(Local {
            name: str_field(p, "name")?.to_string(),
            dir: manifest
                .parent()
                .expect("a manifest is in a directory")
                .to_path_buf(),
            json: p.clone(),
        });
    }
    if locals.is_empty() {
        return Err("the glue crate has no path dependencies: nothing to bundle".into());
    }
    Ok(locals)
}

/// Every file git knows under `dir` (tracked, or untracked and not ignored) that
/// exists, relative to `root`.
fn git_files(root: &Path, dir: &str) -> Result<Vec<PathBuf>, String> {
    let mut cmd = Command::new("git");
    cmd.arg("-C")
        .arg(root)
        .args([
            "ls-files",
            "-z",
            "--cached",
            "--others",
            "--exclude-standard",
            "--",
        ])
        .arg(dir);
    let stdout = run_command(cmd, "git ls-files")?;
    let files: Vec<PathBuf> = stdout
        .split(|&b| b == 0)
        .filter(|s| !s.is_empty())
        .map(|s| PathBuf::from(String::from_utf8_lossy(s).into_owned()))
        .filter(|rel| root.join(rel).is_file())
        .collect();
    if files.is_empty() {
        return Err(format!("git lists no files under {dir}"));
    }
    Ok(files)
}

/// Remove an earlier output; refuse to remove anything else.
fn clear_output(out: &Path) -> Result<(), String> {
    if !out.exists() {
        return Ok(());
    }
    let ours = std::fs::read_to_string(out.join("src/rust/Cargo.toml"))
        .is_ok_and(|s| s.starts_with(GENERATED));
    let empty = out.read_dir().is_ok_and(|mut d| d.next().is_none());
    if !ours && !empty {
        return Err(format!(
            "{} exists and isn't an earlier r-source output; remove it or choose another --out",
            out.display()
        ));
    }
    std::fs::remove_dir_all(out).map_err(|e| format!("remove {}: {e}", out.display()))
}

fn read(path: &Path) -> Result<String, String> {
    std::fs::read_to_string(path).map_err(|e| format!("read {}: {e}", path.display()))
}

fn write(path: &Path, contents: &str) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| format!("mkdir {}: {e}", parent.display()))?;
    }
    std::fs::write(path, contents).map_err(|e| format!("write {}: {e}", path.display()))
}

fn copy(from: &Path, to: &Path) -> Result<(), String> {
    if let Some(parent) = to.parent() {
        std::fs::create_dir_all(parent).map_err(|e| format!("mkdir {}: {e}", parent.display()))?;
    }
    std::fs::copy(from, to)
        .map(|_| ())
        .map_err(|e| format!("copy {} to {}: {e}", from.display(), to.display()))
}

/// A TOML string (JSON's escapes are TOML's).
fn toml_str(s: &str) -> String {
    serde_json::to_string(s).expect("a string serializes")
}

fn toml_list<'a>(items: impl IntoIterator<Item = &'a str>) -> String {
    let items: Vec<String> = items.into_iter().map(toml_str).collect();
    format!("[{}]", items.join(", "))
}

/// The manifest of a bundled workspace crate, from its `cargo metadata` entry: the
/// package fields it inherits from the workspace written out, its library, its
/// normal dependencies (workspace crates by path, as siblings in `crates/`, the
/// rest from crates.io) and its features. Anything that needs more than that (a
/// build script, binaries, other sources) is an error, not something to drop.
/// `origin` names the manifest it comes from, for the header.
fn crate_manifest(pkg: &Value, locals: &BTreeSet<&str>, origin: &str) -> Result<String, String> {
    let name = str_field(pkg, "name")?;
    let dir = Path::new(str_field(pkg, "manifest_path")?)
        .parent()
        .expect("a manifest is in a directory")
        .to_path_buf();
    if !pkg["links"].is_null() {
        return Err(format!("{name}: `links` (a build script) isn't supported"));
    }

    let mut lib = None;
    for target in pkg["targets"]
        .as_array()
        .ok_or("cargo metadata: no targets")?
    {
        let kinds: Vec<&str> = target["kind"]
            .as_array()
            .ok_or("cargo metadata: no target kind")?
            .iter()
            .filter_map(Value::as_str)
            .collect();
        // Tests, benches and examples aren't bundled (only src/ is copied).
        if kinds
            .iter()
            .all(|k| matches!(*k, "test" | "bench" | "example"))
        {
            continue;
        }
        let src = Path::new(str_field(target, "src_path")?);
        if kinds != ["lib"] || src != dir.join("src/lib.rs") || lib.is_some() {
            return Err(format!(
                "{name}: target `{}` ({}, {}) isn't supported; only a library at src/lib.rs is",
                str_field(target, "name")?,
                kinds.join(", "),
                src.display()
            ));
        }
        lib = Some(str_field(target, "name")?);
    }
    let lib = lib.ok_or_else(|| format!("{name}: no library target"))?;

    let mut m = String::new();
    let _ = writeln!(m, "{GENERATED} from {origin}: edit that file instead.");
    m.push_str("\n[package]\n");
    let _ = writeln!(m, "name = {}", toml_str(name));
    let _ = writeln!(m, "version = {}", toml_str(str_field(pkg, "version")?));
    let _ = writeln!(m, "edition = {}", toml_str(str_field(pkg, "edition")?));
    if let Some(v) = pkg["rust_version"].as_str() {
        let _ = writeln!(m, "rust-version = {}", toml_str(v));
    }
    if let Some(v) = pkg["license"].as_str() {
        let _ = writeln!(m, "license = {}", toml_str(v));
    }
    m.push_str("publish = false\n");
    // Only src/ is bundled; don't look for anything else.
    m.push_str("autobins = false\nautoexamples = false\nautotests = false\nautobenches = false\n");
    m.push_str("\n[lib]\n");
    let _ = writeln!(m, "name = {}", toml_str(lib));
    m.push_str("path = \"src/lib.rs\"\n");

    // Dependency lines by target (`None`: every platform), sorted by name.
    let mut sections: BTreeMap<Option<&str>, BTreeMap<&str, String>> = BTreeMap::new();
    for dep in pkg["dependencies"]
        .as_array()
        .ok_or("cargo metadata: no dependencies")?
    {
        let dep_name = str_field(dep, "name")?;
        match dep["kind"].as_str() {
            None => {}
            Some("dev") => continue,
            Some(kind) => {
                return Err(format!(
                    "{name}: {kind}-dependency `{dep_name}` isn't supported"
                ))
            }
        }
        let mut fields = Vec::new();
        if dep["path"].is_string() {
            if !locals.contains(dep_name) {
                return Err(format!(
                    "{name}: path dependency `{dep_name}` isn't one of the bundled crates"
                ));
            }
            fields.push(format!("path = {}", toml_str(&format!("../{dep_name}"))));
        } else if dep["source"].as_str() == Some(CRATES_IO) {
            fields.push(format!("version = {}", toml_str(str_field(dep, "req")?)));
        } else {
            return Err(format!(
                "{name}: dependency `{dep_name}` comes from {}; only crates.io and the \
                 workspace are supported",
                dep["source"]
            ));
        }
        if dep["rename"].is_string() {
            fields.push(format!("package = {}", toml_str(dep_name)));
        }
        if dep["uses_default_features"] == Value::Bool(false) {
            fields.push("default-features = false".into());
        }
        let features: Vec<&str> = dep["features"]
            .as_array()
            .map(|f| f.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        if !features.is_empty() {
            fields.push(format!("features = {}", toml_list(features)));
        }
        if dep["optional"] == Value::Bool(true) {
            fields.push("optional = true".into());
        }
        let key = dep["rename"].as_str().unwrap_or(dep_name);
        let line = format!("{} = {{ {} }}", toml_str(key), fields.join(", "));
        let section = sections.entry(dep["target"].as_str()).or_default();
        if section.insert(key, line).is_some() {
            return Err(format!("{name}: dependency `{key}` is listed twice"));
        }
    }
    for (target, deps) in &sections {
        match target {
            None => m.push_str("\n[dependencies]\n"),
            Some(t) => {
                let _ = writeln!(m, "\n[target.{}.dependencies]", toml_str(t));
            }
        }
        for line in deps.values() {
            let _ = writeln!(m, "{line}");
        }
    }

    if let Some(features) = pkg["features"].as_object().filter(|f| !f.is_empty()) {
        m.push_str("\n[features]\n");
        for (feature, enables) in features {
            let enables = enables
                .as_array()
                .map(|e| e.iter().filter_map(Value::as_str).collect::<Vec<_>>())
                .unwrap_or_default();
            let _ = writeln!(m, "{} = {}", toml_str(feature), toml_list(enables));
        }
    }
    Ok(m)
}

/// The glue crate's manifest with its path dependencies pointed at the bundled
/// crates, as a workspace of its own (so cargo doesn't take a workspace the
/// package is unpacked inside, such as this repository, for its own).
fn glue_manifest(original: &str) -> Result<String, String> {
    let rewritten = original.replace("path = \"../../../crates/", "path = \"crates/");
    if rewritten == original {
        return Err("the glue crate's manifest has no `../../../crates/` path to rewrite".into());
    }
    if rewritten.contains("../") {
        return Err("the glue crate's manifest still names a path outside the package".into());
    }
    if rewritten.lines().any(|l| l.trim() == "[workspace]") {
        return Err("the glue crate's manifest already has a [workspace] table".into());
    }
    Ok(format!(
        "{GENERATED} from r-package/src/rust/Cargo.toml: edit that file instead.\n\n\
         {rewritten}\n\
         # A workspace of its own, with the bundled crates in crates/.\n\
         [workspace]\n"
    ))
}

const COPYRIGHT: &str =
    "Copyright: The authors of the bundled Rust crates, listed in inst/AUTHORS.";

fn with_copyright(description: &str) -> Result<String, String> {
    if description.lines().any(|l| l.starts_with("Copyright:")) {
        return Err("DESCRIPTION already has a Copyright field".into());
    }
    let mut d = description.trim_end().to_string();
    let _ = writeln!(d, "\n{COPYRIGHT}");
    Ok(d)
}

/// `inst/AUTHORS`: each bundled crates.io crate, its license and authors.
fn authors(metadata: &Value) -> Result<String, String> {
    let mut crates = BTreeMap::new();
    for p in metadata["packages"]
        .as_array()
        .ok_or("cargo metadata: no packages")?
    {
        if p["source"].is_null() {
            continue;
        }
        let name = str_field(p, "name")?;
        let version = str_field(p, "version")?;
        let license = p["license"]
            .as_str()
            .unwrap_or("see the license file in its source");
        let who: Vec<&str> = p["authors"]
            .as_array()
            .map(|a| a.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        let who = if who.is_empty() {
            format!("the {name} developers")
        } else {
            who.join(", ")
        };
        crates.insert(
            (name, version),
            format!("{name} {version}\n  License: {license}\n  Authors: {who}\n"),
        );
    }
    let mut a = String::from(
        "gridwell bundles the source of the Rust crates below, in src/rust/vendor.tar.xz,\n\
         each under its own license. The crates in src/rust/crates are gridwell's own\n\
         (MIT; see LICENSE).\n",
    );
    for entry in crates.values() {
        let _ = write!(a, "\n{entry}");
    }
    Ok(a)
}

/// Vendor the crates.io dependencies into `vendor.tar.xz` beside the manifest in
/// `rust_dir`, write `vendor-config.toml`, and return the archive's size.
fn vendor(rust_dir: &Path) -> Result<u64, String> {
    let vendor_dir = rust_dir.join("vendor");
    let mut cmd = cargo();
    cmd.args(["vendor", "--locked", "--quiet", "--manifest-path"])
        .arg(rust_dir.join("Cargo.toml"))
        .arg(&vendor_dir)
        .current_dir(rust_dir);
    run_command(cmd, "cargo vendor")?;

    let mut cmd = Command::new("tar");
    cmd.args(["-cJf", "vendor.tar.xz", "vendor"])
        .current_dir(rust_dir)
        // macOS tar would add AppleDouble `._*` files, which break the vendored
        // crates' checksums.
        .env("COPYFILE_DISABLE", "1")
        .env("XZ_OPT", "-9");
    run_command(cmd, "tar")?;
    std::fs::remove_dir_all(&vendor_dir)
        .map_err(|e| format!("remove {}: {e}", vendor_dir.display()))?;
    write(&rust_dir.join("vendor-config.toml"), VENDOR_CONFIG)?;

    let archive = rust_dir.join("vendor.tar.xz");
    std::fs::metadata(&archive)
        .map(|m| m.len())
        .map_err(|e| format!("{}: {e}", archive.display()))
}

