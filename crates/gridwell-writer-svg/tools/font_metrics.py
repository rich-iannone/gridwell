"""Generate src/metrics.rs: advance widths of the fonts the SVG writer lays out with.

The SVG writer lays text out itself, so it needs real glyph widths:

- **Roboto** (first in the SVG font list): every line is drawn with `textLength`
  set to its Roboto width, so viewers that honor `textLength` draw exactly that
  width whatever font they substitute.
- **Arimo** (metric-compatible with Arial, Helvetica and Liberation Sans): cells
  are sized for the wider of the two per character, so viewers that ignore
  `textLength` (librsvg) and substitute Helvetica or Arial still fit.

Source: https://github.com/google/fonts, `ofl/roboto` (`Roboto[wdth,wght].ttf`,
`Roboto-Italic[wdth,wght].ttf`) and `ofl/arimo` (`Arimo[wght].ttf`,
`Arimo-Italic[wght].ttf`), all under the SIL Open Font License 1.1. Only advance
widths are taken; the fonts are not part of this repository.

    uv run --no-project --with fonttools python tools/font_metrics.py \\
        <dir with the Roboto TTFs> <dir with the Arimo TTFs> > src/metrics.rs
"""

import sys
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

# Scripts and symbols tables actually use; anything else falls back to estimates.
RANGES = [
    (0x0020, 0x007E),  # Basic Latin
    (0x00A0, 0x024F),  # Latin-1, Latin Extended-A/B
    (0x0370, 0x03FF),  # Greek
    (0x0400, 0x04FF),  # Cyrillic
    (0x1E00, 0x1EFF),  # Latin Extended Additional (Vietnamese, ...)
    (0x2010, 0x205E),  # General Punctuation
    (0x2070, 0x209F),  # Superscripts and subscripts
    (0x20A0, 0x20C0),  # Currency
    (0x2100, 0x214F),  # Letterlike symbols
    (0x2150, 0x218F),  # Number forms (fractions)
    (0x2190, 0x21FF),  # Arrows
    (0x2200, 0x22FF),  # Mathematical operators
    (0x25A0, 0x25FF),  # Geometric shapes
]


def advances(path: Path, axes: dict) -> tuple[int, dict[int, int], str]:
    font = TTFont(path)
    version = font["name"].getDebugName(5)
    font = instantiateVariableFont(font, axes)
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    out = {}
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            glyph = cmap.get(cp)
            if glyph is not None:
                out[cp] = hmtx[glyph][0]
    return font["head"].unitsPerEm, out, version


def table(name: str, widths: dict[int, int]) -> str:
    rows = [f"        (0x{cp:04X}, {w})," for cp, w in sorted(widths.items())]
    return f"    pub static {name}: &[(u32, u16)] = &[\n" + "\n".join(rows) + "\n    ];\n"


def module(name: str, doc: str, upright: Path, italic: Path, extra_axes: dict) -> tuple[str, str]:
    upem, versions, tables = None, set(), []
    for style, path, weight in [
        ("REGULAR", upright, 400),
        ("BOLD", upright, 700),
        ("ITALIC", italic, 400),
        ("BOLD_ITALIC", italic, 700),
    ]:
        u, widths, version = advances(path, {"wght": weight, **extra_axes})
        assert upem in (None, u), "units per em differ"
        upem = u
        versions.add(version)
        tables.append(table(style, widths))
    version = ", ".join(sorted(versions))
    body = (
        f"/// {doc} ({version}).\npub mod {name} {{\n"
        f"    /// Font units per em.\n    pub const UNITS_PER_EM: f64 = {upem}.0;\n\n"
        + "\n".join(tables)
        + "}\n"
    )
    return body, version


def main() -> None:
    roboto_dir, arimo_dir = Path(sys.argv[1]), Path(sys.argv[2])
    roboto, _ = module(
        "roboto",
        "Roboto, the font text is drawn at",
        roboto_dir / "Roboto[wdth,wght].ttf",
        roboto_dir / "Roboto-Italic[wdth,wght].ttf",
        {"wdth": 100},
    )
    arimo, _ = module(
        "arimo",
        "Arimo, metric-compatible with Arial and Helvetica: cells leave room for it",
        arimo_dir / "Arimo[wght].ttf",
        arimo_dir / "Arimo-Italic[wght].ttf",
        {},
    )
    print("//! Advance widths of Roboto and Arimo (generated by `tools/font_metrics.py`;")
    print("//! do not edit). From https://github.com/google/fonts (`ofl/roboto`,")
    print("//! `ofl/arimo`), licensed under the SIL Open Font License 1.1. Instances at")
    print("//! wght 400 (regular) and 700 (bold), upright and italic (Roboto at wdth 100).")
    print("//! Each table is sorted by code point: `(code point, advance in font units)`.")
    print()
    print(roboto)
    print(arimo, end="")


if __name__ == "__main__":
    main()
